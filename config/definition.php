<?php

declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $definition->rootNode()
        ->children()
            ->scalarNode('admin_prefix')
                ->info('URL prefix of the whole admin area (routes, firewall access_control).')
                ->defaultValue('admin')
                ->cannotBeEmpty()
            ->end()
            ->scalarNode('admin_title')
                ->info('Translation key (or plain text) of the title displayed in the admin layout.')
                ->defaultValue('admin.title')
            ->end()
            ->scalarNode('admin_title_translation_domain')
                ->info('Translation domain of admin_title.')
                ->defaultValue('GingermindsCore')
            ->end()
            ->scalarNode('health_check_path')
                ->info('Public path always answering {"status": "ok"} (CI/monitoring).')
                ->defaultValue('health')
                ->cannotBeEmpty()
            ->end()
            ->arrayNode('security')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('authorized_domains')
                        ->info('Hosts allowed as "Origin" of the admin login form. Empty list disables the check.')
                        ->scalarPrototype()->end()
                        ->defaultValue([])
                    ->end()
                ->end()
            ->end()
            ->arrayNode('api')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('prefix')
                        ->info('Prefix of the API authentication routes (login/logout).')
                        ->defaultValue('api')
                    ->end()
                    ->integerNode('token_ttl')
                        ->info('API token lifetime in seconds, null for no expiration.')
                        ->defaultNull()
                        ->min(60)
                    ->end()
                    ->arrayNode('login_throttling')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->integerNode('max_attempts')->defaultValue(5)->min(1)->end()
                            ->scalarNode('interval')->defaultValue('5 minutes')->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('cache')
                ->addDefaultsIfNotSet()
                ->children()
                    ->booleanNode('enabled')
                        ->info('Global switch of the API response cache of CacheableResourceInterface resources.')
                        ->defaultTrue()
                    ->end()
                    ->integerNode('default_ttl')->defaultValue(3600)->min(0)->end()
                    ->scalarNode('pool')
                        ->info('Tag-aware cache pool service id.')
                        ->defaultValue('gingerminds_core.resource_cache')
                    ->end()
                ->end()
            ->end()
            ->arrayNode('permissions')
                ->info('Extra permission names created by gingerminds:permissions:sync.')
                ->scalarPrototype()->end()
                ->defaultValue([])
            ->end()
            ->arrayNode('resources')
                ->info('Admin resources. Core ones (user, contributor, role, permission) can be overridden key by key.')
                ->useAttributeAsKey('name')
                ->arrayPrototype()
                    ->children()
                        ->scalarNode('entity')->defaultNull()->end()
                        ->scalarNode('controller')->defaultNull()->end()
                        ->scalarNode('form')->defaultNull()->end()
                        ->scalarNode('path')->defaultNull()->end()
                        ->scalarNode('permission')->defaultNull()->end()
                        ->scalarNode('route_prefix')->defaultNull()->end()
                        ->scalarNode('translation_prefix')->defaultNull()->end()
                        ->scalarNode('translation_domain')->defaultNull()->end()
                        ->scalarNode('template_prefix')->defaultNull()->end()
                    ->end()
                ->end()
                ->defaultValue([])
            ->end()
        ->end();
};
